Json workshop_append_record(Json &rows, Json value, bool generate_identity)
{
	if (!rows.is_array())
		throw std::runtime_error("Record destination must be an array");
	if (generate_identity && value.is_object() && value.contains("id"))
	{
		const auto prefix = value.at("id").get<std::string>();
		for (unsigned i = 1;; ++i)
		{
			const auto id = prefix + std::to_string(i);
			bool used = false;
			for (const auto &row : rows)
				used = used || (row.is_object() && row.value("id", Json()) == id);
			if (!used)
			{
				value["id"] = id;
				break;
			}
		}
	}
	rows.push_back(std::move(value));
	return rows.size() - 1;
}
