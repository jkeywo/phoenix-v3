StaticModel compile_model(std::span<const std::uint8_t> bytes)
{
	auto fail = []()
	{
		throw std::runtime_error("model: expected bounded embedded static GLB triangle geometry");
	};
	cgltf_options options{};
	cgltf_data *raw = nullptr;
	if (bytes.size() > 16 * 1024 * 1024 ||
	    cgltf_parse(&options, bytes.data(), bytes.size(), &raw) != cgltf_result_success)
		fail();
	std::unique_ptr<cgltf_data, decltype(&cgltf_free)> data(raw, cgltf_free);
	if (data->file_type != cgltf_file_type_glb || data->nodes_count > 1024 || data->animations_count ||
	    data->skins_count)
		fail();
	for (size_t i = 0; i < data->extensions_required_count; ++i)
		if (std::string(data->extensions_required[i]) != "KHR_materials_emissive_strength")
			fail();
	for (size_t i = 0; i < data->buffers_count; ++i)
		if (data->buffers[i].uri)
			fail();
	for (size_t i = 0; i < data->images_count; ++i)
		if (data->images[i].uri || !data->images[i].buffer_view)
			fail();
	if (cgltf_load_buffers(&options, data.get(), nullptr) != cgltf_result_success ||
	    cgltf_validate(data.get()) != cgltf_result_success)
		fail();
	auto image = [&](cgltf_texture *texture) -> Bytes
	{
		if (!texture)
			return {};
		if (!texture->image || !texture->image->buffer_view)
		{
			fail();
			return {};
		}
		const auto *v = texture->image->buffer_view;
		const auto *p = static_cast<const uint8_t *>(v->buffer->data) + v->offset;
		Bytes out(p, p + v->size);
		decode_asset_image(out);
		return out;
	};
	// Respect the authored default scene: inactive scene/template nodes are not instances.
	std::set<const cgltf_node *> active;
	std::vector<const cgltf_node *> pending;
	for (size_t i = 0; i < data->nodes_count; ++i)
	{
		size_t depth = 0;
		for (auto *p = &data->nodes[i]; p; p = p->parent)
			if (++depth > data->nodes_count)
				fail();
	}
	const auto *scene = data->scene ? data->scene : (data->scenes_count ? &data->scenes[0] : nullptr);
	if (scene)
		for (size_t i = 0; i < scene->nodes_count; ++i)
			pending.push_back(scene->nodes[i]);
	else
		for (size_t i = 0; i < data->nodes_count; ++i)
			if (!data->nodes[i].parent)
				pending.push_back(&data->nodes[i]);
	while (!pending.empty())
	{
		const auto *node = pending.back();
		pending.pop_back();
		if (!active.insert(node).second)
			continue;
		for (size_t i = 0; i < node->children_count; ++i)
			pending.push_back(node->children[i]);
	}
	StaticModel result;
	size_t total = 0, texture_pixels = 0, texture_bytes = 0;
	for (size_t ni = 0; ni < data->nodes_count; ++ni)
	{
		auto &node = data->nodes[ni];
		if (!active.contains(&node) || !node.mesh)
			continue;
		if (node.skin || node.mesh->weights_count)
			fail();
		size_t ancestors = 0;
		for (auto *parent = &node; parent; parent = parent->parent)
			if (++ancestors > data->nodes_count)
				fail();
		float matrix[16];
		cgltf_node_transform_world(&node, matrix);
		for (auto v : matrix)
			if (!std::isfinite(v))
				fail();
		const float det = matrix[0] * (matrix[5] * matrix[10] - matrix[9] * matrix[6]) -
		                  matrix[4] * (matrix[1] * matrix[10] - matrix[9] * matrix[2]) +
		                  matrix[8] * (matrix[1] * matrix[6] - matrix[5] * matrix[2]);
		if (std::abs(det) < 1e-12f)
			fail();
		for (size_t pi = 0; pi < node.mesh->primitives_count; ++pi)
		{
			auto &p = node.mesh->primitives[pi];
			if (p.type != cgltf_primitive_type_triangles || p.targets_count || result.parts.size() >= 256)
				fail();
			const cgltf_accessor *pos = nullptr, *norm = nullptr, *uv = nullptr;
			for (size_t ai = 0; ai < p.attributes_count; ++ai)
			{
				const auto &a = p.attributes[ai];
				if (a.type == cgltf_attribute_type_position)
					pos = a.data;
				if (a.type == cgltf_attribute_type_normal)
					norm = a.data;
				if (a.type == cgltf_attribute_type_texcoord && a.index == 0)
					uv = a.data;
			}
			if (!pos || pos->type != cgltf_type_vec3 ||
			    (norm && (norm->type != cgltf_type_vec3 || norm->count != pos->count)) ||
			    (uv && (uv->type != cgltf_type_vec2 || uv->count != pos->count)))
				fail();
			size_t count = p.indices ? p.indices->count : pos->count;
			total += count;
			if (!count || count % 3 || total > 1500000)
				fail();
			ModelPart part;
			if (p.material)
			{
				auto &m = *p.material;
				if (m.has_pbr_specular_glossiness || m.has_transmission || m.alpha_mode == cgltf_alpha_mode_blend)
					fail();
				for (int i = 0; i < 4; ++i)
					part.tint[i] = m.pbr_metallic_roughness.base_color_factor[i];
				if (m.pbr_metallic_roughness.base_color_texture.texcoord || m.emissive_texture.texcoord)
					fail();
				part.albedo = image(m.pbr_metallic_roughness.base_color_texture.texture);
				part.emissive = image(m.emissive_texture.texture);
				for (int i = 0; i < 3; ++i)
					part.emission[i] =
					    m.emissive_factor[i] * (m.has_emissive_strength ? m.emissive_strength.emissive_strength : 1.f);
			}
			// GPU allocations follow primitives, including shared textures, so bound decoded cost too.
			for (const auto *encoded : {&part.albedo, &part.emissive})
				if (!encoded->empty())
				{
					const auto decoded = decode_asset_image(*encoded);
					texture_pixels += decoded.rgba.size();
					texture_bytes += encoded->size();
					if (texture_pixels > 64 * 1024 * 1024 || texture_bytes > 32 * 1024 * 1024)
						fail();
				}
			for (float value : part.tint)
				if (!std::isfinite(value) || value < 0 || value > 1)
					fail();
			for (float value : part.emission)
				if (!std::isfinite(value) || value < 0 || value > 64)
					fail();
			for (size_t i = 0; i < count; ++i)
			{
				auto index = p.indices ? cgltf_accessor_read_index(p.indices, i) : i;
				if (index >= pos->count)
					fail();
				float v[3]{}, n[3]{0, 1, 0}, t[2]{};
				if (!cgltf_accessor_read_float(pos, index, v, 3) ||
				    (norm && !cgltf_accessor_read_float(norm, index, n, 3)) ||
				    (uv && !cgltf_accessor_read_float(uv, index, t, 2)))
					fail();
				float world[3]{matrix[0] * v[0] + matrix[4] * v[1] + matrix[8] * v[2] + matrix[12],
				               matrix[1] * v[0] + matrix[5] * v[1] + matrix[9] * v[2] + matrix[13],
				               matrix[2] * v[0] + matrix[6] * v[1] + matrix[10] * v[2] + matrix[14]};
				// Cofactor matrix / determinant is the inverse transpose for normals.
				float normal[3]{((matrix[5] * matrix[10] - matrix[9] * matrix[6]) * n[0] +
				                 (matrix[9] * matrix[2] - matrix[1] * matrix[10]) * n[1] +
				                 (matrix[1] * matrix[6] - matrix[5] * matrix[2]) * n[2]) /
				                    det,
				                ((matrix[8] * matrix[6] - matrix[4] * matrix[10]) * n[0] +
				                 (matrix[0] * matrix[10] - matrix[8] * matrix[2]) * n[1] +
				                 (matrix[4] * matrix[2] - matrix[0] * matrix[6]) * n[2]) /
				                    det,
				                ((matrix[4] * matrix[9] - matrix[8] * matrix[5]) * n[0] +
				                 (matrix[8] * matrix[1] - matrix[0] * matrix[9]) * n[1] +
				                 (matrix[0] * matrix[5] - matrix[4] * matrix[1]) * n[2]) /
				                    det};
				for (float x : world)
				{
					if (!std::isfinite(x) || std::abs(x) > 1e6f)
						fail();
					part.positions.push_back(x);
				}
				const auto normal_length = std::hypot(normal[0], normal[1], normal[2]);
				if (!std::isfinite(normal_length) || normal_length < 1e-12f)
					fail();
				for (auto &value : normal)
					value /= normal_length;
				for (float x : normal)
				{
					if (!std::isfinite(x))
						fail();
					part.normals.push_back(x);
				}
				for (float x : t)
				{
					if (!std::isfinite(x))
						fail();
					part.texcoords.push_back(x);
				}
			}
			if (!norm)
				for (size_t i = 0; i < count; i += 3)
				{
					const auto offset = i * 3;
					const auto &v = part.positions;
					const float ax = v[offset + 3] - v[offset], ay = v[offset + 4] - v[offset + 1],
					            az = v[offset + 5] - v[offset + 2];
					const float bx = v[offset + 6] - v[offset], by = v[offset + 7] - v[offset + 1],
					            bz = v[offset + 8] - v[offset + 2];
					const float nx = ay * bz - az * by, ny = az * bx - ax * bz, nz = ax * by - ay * bx;
					const float length = std::sqrt(nx * nx + ny * ny + nz * nz);
					if (!std::isfinite(length) || length < 1e-12f)
						fail();
					for (size_t corner = 0; corner < 3; ++corner)
					{
						part.normals[offset + corner * 3] = nx / length;
						part.normals[offset + corner * 3 + 1] = ny / length;
						part.normals[offset + corner * 3 + 2] = nz / length;
					}
				}
			result.parts.push_back(std::move(part));
		}
	}
	if (result.parts.empty())
		fail();
	return result;
}
void verify_model_render(const Json &render, const Catalog &catalog, const std::string &path)
{
	auto fail = [&](const std::string &why)
	{
		throw std::runtime_error(path + ": " + why);
	};
	if (render.contains("sprite") || render.contains("images") || render.contains("engines"))
		fail("model entities cannot contain sprite representations");
	if (render.contains("model") == render.contains("star"))
		fail("declare exactly one model or procedural star");
	auto vector = [&](const Json &v, bool positive = false)
	{
		if (!v.is_array() || v.size() != 3)
			fail("expected XYZ vector");
		for (const auto &x : v)
			if (!x.is_number() || !std::isfinite(x.get<float>()) || std::abs(x.get<float>()) > 1e6f ||
			    (positive && x.get<float>() <= 0))
				fail("invalid vector");
	};
	if (render.contains("model"))
	{
		const auto &m = render.at("model");
		const auto ref = m.at("asset").get<std::string>();
		if (!catalog.assets.contains(ref))
			fail("unresolved GLB asset");
		compile_model(catalog.assets.at(ref));
		for (const char *key : {"offset", "rotation", "scale"})
			if (m.contains(key))
				vector(m.at(key), std::string(key) == "scale");
	}
	if (render.contains("star"))
	{
		const auto &star = render.at("star");
		for (const char *key : {"surface_colour", "hot_colour", "cell_colour", "halo_colour"})
			if (star.contains(key))
				vector(star.at(key));
		for (const char *key : {"animation_speed", "halo_radius_multiplier"})
			if (star.contains(key) && (!star.at(key).is_number() || !std::isfinite(star.at(key).get<float>()) ||
			                           star.at(key).get<float>() <= 0 || star.at(key).get<float>() > 16))
				fail("invalid star parameter");
	}
	const auto attachments = render.value("attachments", Json::object());
	if (!attachments.is_object() || attachments.size() > 64)
		fail("invalid attachments");
	for (const auto &[name, a] : attachments.items())
	{
		if (!valid_identifier(name))
			fail("invalid attachment name");
		vector(a.at("position"));
		vector(a.at("direction"));
		float length = 0;
		for (auto v : a.at("direction"))
			length += v.get<float>() * v.get<float>();
		if (length < 1e-12f)
			fail("attachment direction must be nonzero");
	}
}
